import { useState } from "ardo/react";
import { ArdoLink as Link } from "ardo/runtime";
import { FerraArticle, FerraCode, FerraCodePair, FerraSelect } from "ferramenta-family/ferra";

import fixture from "../data/check-sample.json";

export function CheckExample() {
  const [selected, setSelected] = useState("broken");
  const sample = fixture.samples.find(({ id }) => id === selected);
  if (!sample) throw new Error("Unknown check example.");
  return (
    <FerraArticle
      id="example"
      title="Three small mistakes. One failed check."
      introduction="A missing anchor, a missing image and a link outside the project path. Compare the same small build before and after fixing its references."
      meta={<Link to="/reference/cli/#usage">Run the check on your own build</Link>}
    >
      <FerraSelect
        label="Build state"
        value={selected}
        options={fixture.samples.map(({ id, label }) => ({ value: id, label }))}
        onChange={(event) => {
          setSelected(event.target.value);
        }}
      />
      <FerraCodePair>
        <FerraCode caption="References in the build" file="index.html">
          {sample.source}
        </FerraCode>
        <div aria-live="polite" aria-atomic="true">
          <FerraCode caption={`Native Rust result · ${sample.summary.issues} issues`}>
            {sample.output}
          </FerraCode>
        </div>
      </FerraCodePair>
      <p>
        The check uses <code>--site-url https://example.org/docs/</code>. The guide contains an{" "}
        <code>id="install"</code> anchor and the build includes <code>assets/logo.svg</code>. One
        external URL is counted, without a request.
      </p>
      <p>
        Both results are generated by the real Rust CLI and checked again in CI. Durations are
        omitted from this small example.
      </p>
    </FerraArticle>
  );
}
